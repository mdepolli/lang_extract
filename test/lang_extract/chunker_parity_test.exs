defmodule LangExtract.ChunkerParityTest do
  @moduledoc """
  Differential tests against upstream langextract's ChunkIterator.

  Fixtures are generated by benchmark/scripts/gen_chunker_fixtures.py,
  which runs each (text, max_char_buffer) case through the upstream
  chunker and freezes every chunk's text and byte offsets. Upstream
  behavior is the executable spec: chunk boundaries must land identically
  across the two libraries — the cross-library benchmarks depend on that.

  Upstream chunks are token intervals: chunk text spans the first token's
  start to the last token's end, so whitespace between chunks belongs to
  no chunk and chunks do not tile the source.
  """
  use ExUnit.Case, async: true

  alias LangExtract.Chunker

  @fixtures "test/fixtures/chunker_parity.json"
            |> File.read!()
            |> Jason.decode!()

  for fixture <- @fixtures do
    @fixture fixture

    test "matches upstream on #{fixture["name"]}" do
      %{"text" => text, "max_char_buffer" => max_chars, "chunks" => expected} = @fixture

      chunks =
        text
        |> Chunker.chunk(max_chunk_chars: max_chars)
        |> Enum.map(
          &%{"text" => &1.text, "byte_start" => &1.byte_start, "byte_end" => &1.byte_end}
        )

      assert chunks == expected
    end
  end
end
